// 每月天数（与每月话题数一一对应）
export const MONTH_DAYS = STAGES.map((s) => s.topics.length);

// 各月起始天（第 1 天起算）
export const MONTH_START_DAY: number[] = (() => {
  const starts: number[] = [];
  let acc = 1;
  for (const d of MONTH_DAYS) {
    starts.push(acc);
    acc += d;
  }
  return starts;
})();

export const TOTAL_DAYS = MONTH_DAYS.reduce((a, b) => a + b, 0); // 366

// 全部话题扁平化，分配全局唯一 id
export const ALL_TOPICS: Topic[] = (() => {
  const list: Topic[] = [];
  let id = 0;
  STAGES.forEach((stage) => {
    stage.topics.forEach((text, i) => {
      list.push({ id: id++, month: stage.month, indexInMonth: i + 1, text });
    });
  });
  return list;
})();

export function stageForMonth(month: number): Stage {
  return STAGES[Math.min(Math.max(month, 1), 12) - 1];
}

// 第 day 天属于第几个月（1~12）
export function monthForDay(day: number): number {
  const d = Math.min(Math.max(day, 1), TOTAL_DAYS);
  for (let m = MONTH_START_DAY.length - 1; m >= 0; m--) {
    if (d >= MONTH_START_DAY[m]) return m + 1;
  }
  return 1;
}

export function topicById(id: number): Topic | undefined {
  return ALL_TOPICS[id];
}
